{
    private Connection $db;

    private QueryCounter $counter;

    private TemporaryDirectory $root;

    private BackupChunkStore $store;

    protected function setUp(): void
    {
        if ((getenv('FORUM_TEST_DB_HOST') ?: '') === '') {
            self::markTestSkipped('FORUM_TEST_DB_HOST not set');
        }

        $this->counter = new QueryCounter();
        $this->db = $this->connect();

        if (!TestDatabase::isDisposable($this->db)) {
            self::fail('Refusing an installed database');
        }

        TestDatabase::reset($this->db);
        $this->root = new TemporaryDirectory();
        mkdir($this->root->path . '/public');
        mkdir($this->root->path . '/private', 0700);
        $this->store = new BackupChunkStore($this->root->path . '/private', $this->root->path . '/public');
        $postgres = SqlDialect::postgres($this->db);
        $this->db->executeStatement($postgres
            ? 'CREATE TABLE backup_fixture (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, '
                . 'payload BYTEA NULL, amount DECIMAL(20,6) NOT NULL)'
            : 'CREATE TABLE backup_fixture (id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY, '
                . 'payload LONGBLOB NULL, amount DECIMAL(20,6) NOT NULL) ENGINE=InnoDB');
        $this->db->insert('backup_fixture', ['id' => '9007199254740993', 'payload' => "\0\xffemoji \u{1F600}",
            'amount' => '12345678901234.123456'], ['payload' => ParameterType::BINARY]);

        if ($postgres) {
            // MySQL moves AUTO_INCREMENT past an explicit id by itself.
            $this->db->executeStatement(
                "SELECT setval(pg_get_serial_sequence('backup_fixture', 'id'), 9007199254740993)",
            );
        }

        $this->db->insert('backup_fixture', ['payload' => null, 'amount' => '0.000000']);
        $this->db->executeStatement(
            'CREATE TABLE backup_fixture_child (id INT PRIMARY KEY, parent_id BIGINT NOT NULL, '
                . 'FOREIGN KEY (parent_id) REFERENCES backup_fixture(id))' . ($postgres ? '' : ' ENGINE=InnoDB'),
        );
        $this->db->insert('backup_fixture_child', ['id' => 1, 'parent_id' => '9007199254740993']);
    }

    protected function tearDown(): void
    {
        if (isset($this->root)) {
            $this->root->remove();
        }

        if (isset($this->db)) {
            TestDatabase::release($this->db);
        }
    }

    public function testFullDatabaseAndFilesRestoreWithDurableReference(): void
    {
        $journal = new UpdateJournal($this->db);
        $now = new DateTimeImmutable('now');
        $id = $journal->begin('backup-drill', str_repeat('a', 64), $now);
        $token = $journal->claim($id, $now);
        $run = $journal->find($id);

        $stages = [UpdateStage::Checked, UpdateStage::Downloaded, UpdateStage::Verified, UpdateStage::Staged];

        foreach ($stages as $stage) {
            $run = $journal->advance($id, $token, $run->revision, $stage, $now);
        }

        $this->root->write('app/config/maintenance.lock', '');
        $this->root->write('app/config/local.php', 'fixture configuration');
        $large = str_repeat("binary\0", 160000);
        $this->root->write('app/public/data.bin', $large);
        $expected = $this->rows('SELECT * FROM backup_fixture ORDER BY id');
        $beforeTables = $this->db->createSchemaManager()->listTableNames();
        $schemas = [];
        $contents = [];

        foreach ($beforeTables as $table) {
            $quoted = $this->db->quoteIdentifier($table);
            $schemas[$table] = $this->schemaOf($table);
            $contents[$table] = $this->rows('SELECT * FROM ' . $quoted);
        }

        $coordinator = new UpdateBackup(DatabaseBackups::for($this->db), $journal);
        $run = $coordinator->export($id, $token, $run->revision, $this->store, $this->root->path . '/app', [
            'config/local.php',
            'public/data.bin',
        ]);
        self::assertSame(UpdateStage::BackedUp, $run->stage);
        $handle = (new UpdateJournal($this->db))->backup($id);
        self::assertNotNull($handle);
        $manifest = json_decode($this->store->read($handle['id'], $handle['digest']), true, 32, JSON_THROW_ON_ERROR);
        TestDatabase::dropAll($this->db);
        DatabaseBackups::for($this->db)->restore($this->store, $handle);
        self::assertSame($beforeTables, $this->db->createSchemaManager()->listTableNames());
        self::assertSame($expected, $this->rows('SELECT * FROM backup_fixture ORDER BY id'));
        foreach ($beforeTables as $table) {
            $quoted = $this->db->quoteIdentifier($table);
            self::assertSame($schemas[$table], $this->schemaOf($table));
            self::assertSame($contents[$table], $this->rows('SELECT * FROM ' . $quoted));
        }

        try {
            $this->db->insert('backup_fixture_child', ['id' => 2, 'parent_id' => 99]);
            self::fail('Restored foreign key must reject an orphan');
        } catch (ForeignKeyConstraintViolationException) {
            self::assertTrue(true);
        }

        mkdir($this->root->path . '/restored', 0700);
        FileBackup::restore($this->store, $manifest['files'], $this->root->path . '/restored');
        self::assertSame($large, file_get_contents($this->root->path . '/restored/public/data.bin'));
        self::assertSame('fixture configuration', file_get_contents($this->root->path . '/restored/config/local.php'));
        if (!SqlDialect::postgres($this->db)) {
            self::assertSame(1, (int) $this->db->fetchOne('SELECT @@FOREIGN_KEY_CHECKS'));
        }

        $this->db->insert('backup_fixture', ['payload' => '', 'amount' => '1.000000']);
        self::assertSame('9007199254740995', $this->db->lastInsertId());
    }

    public function testInterruptedExportReleasesLocksAndCanRestart(): void
    {
        $calls = 0;

        try {
            DatabaseBackups::for($this->db)->export($this->store, static function () use (&$calls): void {
                if (++$calls === 4) {
                    throw new RuntimeException('fixture_interruption');
                }
            });
            self::fail('Expected interruption');
        } catch (RuntimeException $failure) {
            self::assertSame('fixture_interruption', $failure->getMessage());
        }

        $this->db->insert('backup_fixture', ['amount' => '2.000000']);
        $handle = DatabaseBackups::for($this->db)->export($this->store, static function (): void {
        });
        self::assertSame(32, strlen($handle['id']));
    }

    public function testConcurrentWriterCannotCrossTheSnapshot(): void
    {
        $other = $this->connect();
        $postgres = SqlDialect::postgres($this->db);
        $other->executeStatement($postgres ? "SET lock_timeout = '1s'" : 'SET SESSION lock_wait_timeout = 1');
        $calls = 0;
        $blocked = false;
        $handle = DatabaseBackups::for($this->db)->export($this->store, function () use (
            $other,
            &$calls,
            &$blocked,
        ): void {
            if (++$calls !== 2) {
                return;
            }

            try {
                $other->insert('backup_fixture', ['amount' => '3.000000']);
            } catch (Throwable) {
                $blocked = true;
            }
        });
        if ($postgres) {
            // PostgreSQL reads one snapshot instead of locking: the writer goes on, the backup does not see it.
            self::assertFalse($blocked);
            $manifest = json_decode(
                $this->store->read($handle['id'], $handle['digest']),
                true,
                32,
                JSON_THROW_ON_ERROR,
            );
            self::assertSame(2, array_column($manifest['tables'], null, 'name')['backup_fixture']['rows']);
        } else {
            self::assertTrue($blocked);
        }

        $other->insert('backup_fixture', ['amount' => '3.000000']);
        $other->close();
    }

    public function testCorruptChunkIsRejectedBeforeRestoreMutatesDatabase(): void
    {
        $handle = DatabaseBackups::for($this->db)->export($this->store, static function (): void {
        });
        $manifest = json_decode($this->store->read($handle['id'], $handle['digest']), true, 32, JSON_THROW_ON_ERROR);

        foreach ($manifest['tables'] as $table) {
            if ($table['chunks'] !== []) {
                $chunk = $table['chunks'][0];
                file_put_contents($this->root->path . '/private/' . $chunk['id'] . '.chunk', 'corrupt');
                break;
            }
        }

        TestDatabase::dropAll($this->db);

        try {
            DatabaseBackups::for($this->db)->restore($this->store, $handle);
            self::fail('Expected integrity rejection');
        } catch (RuntimeException $failure) {
            self::assertSame('backup_chunk_integrity_failed', $failure->getMessage());
        }

        self::assertSame([], $this->db->createSchemaManager()->listTableNames());
    }

    public function testRestoreRefusesAnOccupiedDatabase(): void
    {
        $this->expectExceptionMessage('backup_restore_requires_empty_database');
        DatabaseBackups::for($this->db)->restore($this->store, ['id' => '', 'digest' => '']);
    }

    public function testExpiredLeaseCannotPublishACompleteBackup(): void
    {
        $journal = new UpdateJournal($this->db);
        $past = new DateTimeImmutable('-1 hour');
        $id = $journal->begin('expired', str_repeat('b', 64), $past);
        $token = $journal->claim($id, $past);
        $this->expectExceptionMessage('update_backup_lease_lost');
        $journal->assertBackupLease($id, $token, $journal->find($id)->revision);
    }

    public function testLargeTableStreamsAcrossChunks(): void
    {
        $this->db->beginTransaction();

        foreach (range(1, 300) as $index) {
            $this->db->insert('backup_fixture', ['payload' => str_repeat('x', 4096), 'amount' => '1.000000']);
        }

        $this->db->commit();
        $handle = DatabaseBackups::for($this->db)->export($this->store, static function (): void {
        });
        $manifest = json_decode($this->store->read($handle['id'], $handle['digest']), true, 32, JSON_THROW_ON_ERROR);
        $tables = array_column($manifest['tables'], null, 'name');
        self::assertGreaterThan(1, count($tables['backup_fixture']['chunks']));
        TestDatabase::dropAll($this->db);
        DatabaseBackups::for($this->db)->restore($this->store, $handle);
        self::assertSame(302, (int) $this->db->fetchOne('SELECT COUNT(*) FROM backup_fixture'));
    }

    public function testFailedFileCaptureNeverAdvancesTheJournal(): void
    {
        $journal = new UpdateJournal($this->db);
        $now = new DateTimeImmutable('now');
        $id = $journal->begin('file-failure', str_repeat('c', 64), $now);
        $token = $journal->claim($id, $now);
        $run = $journal->find($id);

        $stages = [UpdateStage::Checked, UpdateStage::Downloaded, UpdateStage::Verified, UpdateStage::Staged];

        foreach ($stages as $stage) {
            $run = $journal->advance($id, $token, $run->revision, $stage, $now);
        }

        $coordinator = new UpdateBackup(DatabaseBackups::for($this->db), $journal);

        foreach (['backup_maintenance_required', 'backup_source_invalid'] as $expected) {
            try {
                $coordinator->export(
                    $id,
                    $token,
                    $run->revision,
                    $this->store,
                    $this->root->path . '/app',
                    ['missing'],
                );
                self::fail('Expected refused capture');
            } catch (RuntimeException $failure) {
                self::assertSame($expected, $failure->getMessage());
            }

            self::assertNull($journal->backup($id));
            self::assertSame(UpdateStage::Staged, $journal->find($id)->stage);
            $this->root->write('app/config/maintenance.lock', '');
        }

        self::assertFileExists($this->root->path . '/app/config/maintenance.lock');
    }

