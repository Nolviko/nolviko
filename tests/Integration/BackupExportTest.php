        DatabaseBackups::for($this->db)->export($this->store, static function (): void {
        });
    }

    public function testSnapshotBenchmark(): void
    {
        $report = BenchmarkHarness::measure(fn(): array => DatabaseBackups::for($this->db)->export(
            $this->store,
            static function (): void {
            },
        ), 10, 1);
        $this->counter->count = 0;
        $handle = DatabaseBackups::for($this->db)->export($this->store, static function (): void {
        });
        $report['queries'] = $this->counter->count;
        $manifest = json_decode($this->store->read($handle['id'], $handle['digest']), true, 32, JSON_THROW_ON_ERROR);
        $report['tables'] = count($manifest['tables']);
        $report['rows'] = $manifest['rows'];
        $report['bytes'] = $manifest['bytes'];
        if (SqlDialect::postgres($this->db)) {
            // Catalog reads per table (columns, constraints, indexes, identity) plus the rows: bounded, linear.
            self::assertLessThanOrEqual(12 + 6 * count($manifest['tables']), $report['queries']);
        } else {
            self::assertSame(11 + 3 * count($manifest['tables']), $report['queries']);
        }
        self::assertGreaterThan(0, $report['p50_ms']);
        fwrite(STDERR, 'backup_snapshot ' . json_encode($report, JSON_THROW_ON_ERROR) . "\n");
    }

    private function connect(): Connection
    {
        return ConnectionFactory::create(new Config(
            TestDatabase::driver(),
            (string) getenv('FORUM_TEST_DB_HOST'),
            null,
            (string) getenv('FORUM_TEST_DB_NAME'),
            (string) getenv('FORUM_TEST_DB_USER'),
            new Secret((string) getenv('FORUM_TEST_DB_PASSWORD')),
            new Secret(str_repeat('s', 32)),
        ), [$this->counter]);
    }

    private static function canonicalSchema(string $ddl): string
    {
        // MySQL renders ALTER-added text columns differently after CREATE replay. This collation already
        // fixes the character set; retain every other DDL byte, including different charsets/collations.
        return str_replace(
            'CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci',
            'COLLATE utf8mb4_unicode_ci',
            $ddl,
        );
    }

    /**
     * Rows with binary values read out (PostgreSQL returns `bytea` as a stream).
     *
     * @return list<array<string, mixed>>
     */
    private function rows(string $sql): array
    {
        return array_map(static fn(array $row): array => array_map(
            static fn(mixed $value): mixed => is_resource($value) ? stream_get_contents($value) : $value,
            $row,
        ), $this->db->fetchAllAssociative($sql));
    }

    /** A comparable description of a table's definition on either backend. */
    private function schemaOf(string $table): string
    {
        if (!SqlDialect::postgres($this->db)) {
            $ddl = $this->db->fetchNumeric('SHOW CREATE TABLE ' . $this->db->quoteIdentifier($table));

            return self::canonicalSchema($ddl[1]);
        }

        $parts = [
            ...$this->db->fetchFirstColumn(
                "SELECT column_name || ' ' || data_type || ' ' || is_nullable || ' ' || COALESCE(column_default, '') "
                    . "|| ' ' || is_identity || ' ' || is_generated || ' ' || COALESCE(collation_name, '') "
                    . 'FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ? '
                    . 'ORDER BY ordinal_position',
                [$table],
            ),
            ...$this->db->fetchFirstColumn(
                "SELECT conname || ' ' || pg_get_constraintdef(oid) FROM pg_constraint "
                    . 'WHERE conrelid = CAST(? AS regclass) ORDER BY conname',
                [$this->db->quoteIdentifier($table)],
            ),
            ...$this->db->fetchFirstColumn(
                'SELECT indexdef FROM pg_indexes WHERE schemaname = current_schema() AND tablename = ? '
                    . 'ORDER BY indexname',
                [$table],
            ),
        ];

        return implode("\n", $parts);
    }
