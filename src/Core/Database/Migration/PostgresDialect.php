<?php

declare(strict_types=1);

namespace Nolviko\Core\Database\Migration;

/**
 * PostgreSQL 16 backend of the core migrations (2026-11-14). Like MariaDbDialect, the migrations keep one set of
 * MySQL 8.4 statements; this class rewrites the small DDL vocabulary they use into PostgreSQL: identity columns
 * for AUTO_INCREMENT, TIMESTAMP(6) for DATETIME(6), SMALLINT flags, TEXT/BYTEA for the MySQL text and binary
 * types, binary (`"C"`) collation for the ascii_bin/utf8mb4_bin identity columns, inline indexes as separate
 * CREATE INDEX statements (index names are schema-wide in PostgreSQL; the core names are already unique), a
 * stored generated column for the one virtual column, and LOCALTIMESTAMP for the MySQL clock
 * functions (the session time zone is UTC, PostgresSession). An explicit-id seed insert is followed by
 * moving the identity sequence past it. Migrations with native PostgreSQL statements (search, task indexes)
 * are used as they are; this class only sees the MySQL ones. It is not a general SQL translator: a statement
 * outside this vocabulary fails loudly with `migration_postgres_untranslated`.
 */
final class PostgresDialect
{
    public const BACKEND = 'postgresql';

    /** MySQL's `UTC_TIMESTAMP(6)` for runtime SQL; independent of the session time zone. */
    public const CLOCK_FUNCTION = 'CREATE OR REPLACE FUNCTION utc_timestamp(integer) RETURNS timestamp(6) '
        . "LANGUAGE sql STABLE AS \$\$ SELECT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::timestamp(6) \$\$";

    private const TYPES = [
        '/\bBIGINT UNSIGNED\b/' => 'BIGINT',
        '/\bTINYINT(\(\d+\))?/' => 'SMALLINT',
        '/\bMEDIUMINT\b/' => 'INTEGER',
        '/\b(MEDIUMTEXT|LONGTEXT|TINYTEXT)\b/' => 'TEXT',
        '/\b(VARBINARY|BINARY)\(\d+\)/' => 'BYTEA',
        '/\b(MEDIUMBLOB|LONGBLOB|TINYBLOB|BLOB)\b/' => 'BYTEA',
        '/\bDATETIME\((\d)\)/' => 'TIMESTAMP($1)',
        '/\bDATETIME\b/' => 'TIMESTAMP(0)',
        '/\bDOUBLE\b(?! PRECISION)/' => 'DOUBLE PRECISION',
        '/\bJSON\b/' => 'JSONB',
        '/ CHARACTER SET (ascii|utf8mb4|binary) COLLATE (ascii_bin|utf8mb4_bin)\b/' => ' COLLATE "C"',
        '/ CHARACTER SET (ascii|utf8mb4)\b/' => '',
        '/ COLLATE utf8mb4_\w+/' => '',
        '/\s*ENGINE\s*=\s*InnoDB(\s+DEFAULT CHARSET\s*=\s*\w+)?(\s+COLLATE\s*=\s*\w+)?/' => '',
        '/\bUTC_TIMESTAMP\((\d)\)/' => 'LOCALTIMESTAMP($1)',
        '/\bCURRENT_TIMESTAMP\((\d)\)/' => 'LOCALTIMESTAMP($1)',
        '/ AFTER [a-z_]+/' => '',
    ];

    private const UNTRANSLATED = '/\b(AUTO_INCREMENT|ENGINE|CHARSET|UNSIGNED|VIRTUAL|FULLTEXT|INSERT IGNORE|'
        . 'ON DUPLICATE KEY|'
        . 'UTC_TIMESTAMP|IF\(|MODIFY|CHANGE COLUMN|utf8mb4|ascii_bin)\b/';

    /**
     * @param list<string> $mysql Statements written for MySQL 8.4.
     *
     * @return list<string>
     *
     * @throws MigrationException `migration_postgres_untranslated` for a construct outside the vocabulary.
     */
    public static function translate(array $mysql): array
    {
        $out = [];

        foreach ($mysql as $statement) {
            foreach (self::statement($statement) as $translated) {
                if (preg_match(self::UNTRANSLATED, $translated) === 1) {
                    throw new MigrationException('migration_postgres_untranslated');
                }

                $out[] = $translated;
            }
        }

        return $out;
    }

    /** @return list<string> */
    private static function statement(string $sql): array
    {
        // A table option `AUTO_INCREMENT=n` (0005 usergroups: custom groups from 100) is the identity's start.
        $start = '';

        if (preg_match('/ AUTO_INCREMENT=(\d+)$/', $sql, $match) === 1) {
            $start = ' (START WITH ' . $match[1] . ')';
            $sql = substr($sql, 0, -strlen($match[0]));
        }

        $sql = (string) preg_replace(
            '/\bBIGINT NOT NULL AUTO_INCREMENT\b/',
            'BIGINT GENERATED BY DEFAULT AS IDENTITY' . $start . ' NOT NULL',
            $sql,
        );
        // The one virtual column (0006 usergroup_members.primary_user_id): PostgreSQL 16 only stores them.
        $sql = (string) preg_replace(
            '/GENERATED ALWAYS AS \(IF\(([^,]+), ([^,]+), NULL\)\) VIRTUAL/',
            'GENERATED ALWAYS AS (CASE WHEN $1 THEN $2 END) STORED',
            $sql,
        );

        foreach (self::TYPES as $pattern => $replacement) {
            $sql = (string) preg_replace($pattern, $replacement, $sql);
        }

        if (preg_match('/^CREATE TABLE (IF NOT EXISTS )?([a-z_]+) \(/', $sql, $match) === 1) {
            return self::createTable($sql, $match[2]);
        }

        if (preg_match('/^ALTER TABLE ([a-z_]+) ADD INDEX ([a-z_]+) (\(.+\))$/s', $sql, $match) === 1) {
            return ['CREATE INDEX ' . $match[2] . ' ON ' . $match[1] . ' ' . $match[3]];
        }

        if (preg_match('/^INSERT INTO ([a-z_]+) \(id,/', $sql, $match) === 1) {
            return [$sql, self::sequence($match[1])];
        }

        return [$sql];
    }

    /**
     * Inline `INDEX name (...)`, `KEY name (...)` and `UNIQUE KEY|INDEX name (...)` become statements after the
     * table; constraints (`CONSTRAINT x UNIQUE (...)`, keys, checks) stay inline.
     *
     * @return list<string>
     */
    private static function createTable(string $sql, string $table): array
    {
        $open = strpos($sql, '(');
        $close = strrpos($sql, ')');

        if ($open === false || $close === false) {
            throw new MigrationException('migration_postgres_untranslated');
        }

        $kept = [];
        $indexes = [];

        foreach (self::split(substr($sql, $open + 1, $close - $open - 1)) as $part) {
            $part = trim($part);

            if (preg_match('/^(UNIQUE (?:KEY|INDEX)|INDEX|KEY) ([a-z_]+) (\(.+\))$/s', $part, $match) === 1) {
                $indexes[] = (str_starts_with($match[1], 'UNIQUE') ? 'CREATE UNIQUE INDEX ' : 'CREATE INDEX ')
                    . $match[2] . ' ON ' . $table . ' ' . $match[3];

                continue;
            }

            $kept[] = $part;
        }

        return [substr($sql, 0, $open + 1) . implode(', ', $kept) . ')' . rtrim(substr($sql, $close + 1)),
            ...$indexes];
    }

    /**
     * Moves the identity sequence past explicitly inserted ids (seed rows), never back: like MySQL, a table
     * that starts at 100 keeps 100 when ids 1 to 4 are seeded.
     */
    private static function sequence(string $table): string
    {
        return 'SELECT setval(x.s, x.m) FROM (SELECT pg_get_serial_sequence(\'' . $table . '\', \'id\') AS s, '
            . '(SELECT MAX(id) FROM ' . $table . ') AS m) x WHERE x.m IS NOT NULL AND x.m >= (SELECT '
            . 'COALESCE(q.last_value, q.start_value) FROM pg_sequences q '
            . "WHERE q.schemaname || '.' || q.sequencename = x.s)";
    }

    /**
     * Splits a column list at top-level commas.
     *
     * @return list<string>
     */
    private static function split(string $body): array
    {
        $parts = [];
        $depth = 0;
        $quoted = false;
        $current = '';

        foreach (str_split($body) as $char) {
            if ($char === "'") {
                $quoted = !$quoted;
            } elseif (!$quoted && $char === '(') {
                $depth++;
            } elseif (!$quoted && $char === ')') {
                $depth--;
            } elseif (!$quoted && $depth === 0 && $char === ',') {
                $parts[] = $current;
                $current = '';

                continue;
            }

            $current .= $char;
        }

        $parts[] = $current;

        return $parts;
    }
}
